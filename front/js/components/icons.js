/** Constrói a string SVG de um nó [tag, atributos, ...filhos]. */
function renderizarNodo(nodo) {
  const [tag, atributos = {}, ...filhos] = nodo
  const lista = Object.entries(atributos)
    .filter(([chave]) => chave !== 'key')
    .map(([chave, valor]) => ` ${chave}="${valor}"`)
    .join('')
  return `<${tag}${lista}>${filhos.map(renderizarNodo).join('')}</${tag}>`
}

/**
 * Devolve o SVG do ícone como string.
 * @param {string} nome Nome do ícone em PascalCase (ex.: 'ClipboardList')
 * @param {string} [classe] Classes CSS adicionais (ex.: 'ic ic--16')
 * @param {string} [rotulo] Acessibilidade: texto alternativo; vazio = aria-hidden
 */
export function icone(nome, classe = '', rotulo = '') {
  const nodo = NODOS[nome]
  if (!nodo) return ''
  const atributos = classe ? ` ${ATRIBUTOS_PADRAO} class="${classe}"` : ` ${ATRIBUTOS_PADRAO}`
  const aria = rotulo ? ` role="img" aria-label="${rotulo}"` : ' aria-hidden="true"'
  return `<svg${atributos}${aria}>${nodo.map(renderizarNodo).join('')}</svg>`
}

